#!/usr/bin/env python3
"""The one list of places we rent in, from data/destinations.txt, written out
for the two places that need it in code:

  lib/destinations.js   ES module, imported by api/lead.js
  crm/destinations.js   plain script, loaded by crm/index.html before app.js

Run after editing data/destinations.txt:  python3 tools/destinations.py
destinations.html is built from the same file with the rent-list builder.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGIONS = ["USA & Canada", "Caribbean", "Europe", "Latin America", "Asia, Africa & Oceania", "Private Islands"]

def place_for(label):
    # The value the Destinations page sends to the contact form.
    # "California, Malibu" -> "Malibu, California"; "France, Rest of France" -> "France"
    if ", " in label:
        a, b = label.split(", ", 1)
        if b.startswith("Rest of "): return b[len("Rest of "):]
        return f"{b}, {a}"
    if label.startswith("Rest of "): return label[len("Rest of "):]
    return label

def country_for(region, label):
    head = label.split(", ", 1)[0]
    if region == "USA & Canada":
        return "Canada" if head == "Canada" else "United States"
    if region == "Private Islands" or label.startswith("Rest of "):
        return None
    return head

rows, region = [], None
for raw in open(os.path.join(ROOT, "data", "destinations.txt"), encoding="utf-8"):
    line = raw.strip()
    if not line: continue
    if line in REGIONS:
        region = line; continue
    rows.append({"label": line, "place": place_for(line), "country": country_for(region, line), "region": region})

countries = sorted({r["country"] for r in rows if r["country"]})
body = json.dumps(rows, ensure_ascii=False, indent=2)
head = "// Generated by tools/destinations.py from data/destinations.txt. Do not edit.\n"
open(os.path.join(ROOT, "lib", "destinations.js"), "w", encoding="utf-8").write(
    head + "export const DESTINATIONS = " + body + ";\n"
    + "export const DESTINATION_COUNTRIES = " + json.dumps(countries, ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "crm", "destinations.js"), "w", encoding="utf-8").write(
    head + "const NQL_DESTINATIONS = " + body + ";\n"
    + "const NQL_DESTINATION_COUNTRIES = " + json.dumps(countries, ensure_ascii=False) + ";\n")
print(f"{len(rows)} places, {len(countries)} countries", file=sys.stderr)
