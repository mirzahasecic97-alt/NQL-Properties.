#!/usr/bin/env python3
"""data/events.json is the public list of the events we post around. This
writes it out as js/upcoming-data.js for the homepage row. Run after editing
the JSON:  python3 tools/events.py
(The CRM's marketing_events table carries the same events with the posting
dates; keep the two in step by hand when an event moves.)"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
events = json.load(open(os.path.join(ROOT, "data", "events.json"), encoding="utf-8"))
out = "// Generated by tools/events.py from data/events.json. Do not edit.\nwindow.NQL_EVENTS = " + json.dumps(events, ensure_ascii=False) + ";\n"
open(os.path.join(ROOT, "js", "upcoming-data.js"), "w", encoding="utf-8").write(out)
print(len(events), "events")
